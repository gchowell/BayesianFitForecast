#------------------------------------------------------------------------------#
# check.IC.R — Validate the initial conditions ---------------------------------
#------------------------------------------------------------------------------#
# About: `check.IC()` receives the initial-condition expressions (already       #
# translated to internal identifiers, e.g. "N - i0"), the parameter names and  #
# the right-hand sides of the ODE system. It returns                           #
#   list(IC, vars.init)                                                        #
# where IC is the vector written to the options file (numbers, or expression   #
# strings) and vars.init is 1 when every initial condition is a plain number   #
# (passed to Stan as data) and 0 otherwise (computed inside the Stan program   #
# from the parameters, so parameters such as i0 can be estimated).             #
#                                                                              #
# Errors are raised (with a readable message) when an initial condition uses   #
# an unknown symbol or cannot be evaluated. The former restrictions ("a        #
# parameter used in the initial conditions and in the ODE must be fixed" and   #
# "a parameter used only in the initial conditions must be estimated") are no  #
# longer needed: the Stan program generated by stancreator.R declares every    #
# parameter (fixed or estimated) by name wherever the initial conditions are   #
# evaluated.                                                                   #
#------------------------------------------------------------------------------#

check.IC <- function(ic.list, params.list, equations.list, fixedStatus, initParam) {

  ic.list <- as.character(unlist(ic.list))
  params.list <- as.character(params.list)
  allowed_functions <- c("exp", "log", "sqrt", "pow", "abs", "fmax", "fmin", "pi", "square", "inv")

  IC.out <- vector("list", length(ic.list))
  all_numeric <- TRUE

  for (i in seq_along(ic.list)) {

    expr_txt <- gsub("\\s+", "", ic.list[i])
    if (!nzchar(expr_txt)) {
      stop(sprintf("initial condition %d is empty", i))
    }

    # Symbols used in the expression
    tokens <- unique(regmatches(expr_txt, gregexpr("[A-Za-z][A-Za-z0-9_]*", expr_txt))[[1]])
    unknown <- tokens[!(tokens %in% params.list) & !(tolower(tokens) %in% allowed_functions)]
    if (length(unknown) > 0) {
      stop(sprintf("initial condition %d uses '%s', which is not a parameter (define it in step 5)",
                   i, paste(unknown, collapse = "', '")))
    }

    param_tokens <- tokens[tokens %in% params.list]

    if (length(param_tokens) == 0) {
      # Purely numeric expression: evaluate it
      value <- tryCatch(eval(parse(text = expr_txt), envir = new.env(parent = baseenv())),
                        error = function(e) NA_real_)
      if (length(value) != 1 || is.na(value) || !is.finite(value)) {
        stop(sprintf("initial condition %d ('%s') is not a valid number", i, ic.list[i]))
      }
      IC.out[[i]] <- as.numeric(value)
    } else {
      # Expression with parameters: keep it as a string for the Stan program
      # (check that it parses as an expression)
      ok <- tryCatch({ parse(text = expr_txt); TRUE }, error = function(e) FALSE)
      if (!ok) stop(sprintf("initial condition %d ('%s') could not be parsed", i, ic.list[i]))
      IC.out[[i]] <- expr_txt
      all_numeric <- FALSE
    }
  }

  list(IC.out, if (all_numeric) 1 else 0)
}
